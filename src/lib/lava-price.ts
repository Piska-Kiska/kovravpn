// Сумма к списанию по линии lava.top. ЧИСТЫЕ ВЫЧИСЛЕНИЯ И БОЛЬШЕ НИЧЕГО:
// ни сети, ни базы, ни окружения.
//
// Отдельным файлом от `lava-purchase.ts` не для красоты. Ту же самую сумму
// обязана показать кнопка на панели, то есть клиентский компонент, а
// `lava-purchase.ts` тянет redis — импортируй его страница, и клиент Upstash
// уехал бы в браузерный бандл.
//
// Правило, ради которого всё это и разделено: показ и списание считаются ОДНИМ
// выражением. Посчитай их порознь — и покупатель увидит одно, а заплатит
// другое; на соседнем проекте это уже случалось, там витрина обещала €13.9, а
// счёт уходил на $15.30.

import type { LavaCurrency } from "./lava-methods";

/**
 * Евро за доллар. ЗАДАНО ВРУЧНУЮ И НАМЕРЕННО НЕ БЕРЁТСЯ ИЗ ВНЕШНЕГО API:
 * цена не должна меняться между открытием страницы и оплатой.
 *
 * ЭТО ЧИСЛО ТРАТИТ ДЕНЬГИ. Прайс Kovra задан в долларах, и по нему считается
 * сумма евровых счетов — тех, которыми платят через SEPA, iDEAL и MB WAY.
 * Поставить 0.80 при рынке 0.92 значит продать европейцу на 13% дешевле и
 * заметить это по выручке, а не по витрине.
 */
export const EUR_PER_USD = 0.92;

/** Сумма к списанию в валюте счёта. */
export function chargeIn(priceUsd: number, currency: LavaCurrency): number {
  // Доллар — родная валюта прайса: платим ровно то, что написано на кнопке,
  // без округлений. 11.99 обязано остаться 11.99, а не стать 12.
  if (currency === "USD") return Math.round(priceUsd * 100) / 100;
  if (currency === "EUR") return Math.round(priceUsd * EUR_PER_USD * 100) / 100;
  // Рублёвых способов в каталоге линии нет вовсе, и RUB может появиться здесь
  // только ошибкой вызывающего. Молча посчитать «как-нибудь» — худшее, что
  // можно сделать с суммой платежа.
  throw new Error(`lava: unsupported charge currency ${currency}`);
}

/** Подпись суммы на кнопке. Тот же расчёт, что уйдёт в счёт. */
export function formatCharge(priceUsd: number, currency: LavaCurrency): string {
  const value = chargeIn(priceUsd, currency);
  const shown = value.toFixed(2);
  return currency === "EUR" ? `€${shown}` : `$${shown}`;
}
