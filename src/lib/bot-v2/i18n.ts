/** Every language's dictionary; exported for the completeness test and the screen harness. */
export const V2_DICTS: Readonly<Record<BotLang, V2Dict>> = { en, ru, es, de, fr };

export const V2_KEYS: readonly V2Key[] = Object.keys(en) as V2Key[];

export type TrVars = Readonly<Record<string, string | number>>;

/** Escape text for Telegram HTML. */
export function escapeHtml(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/**
 * Translate `key` into `lang` and fill `{var}` placeholders. Variables are
 * escaped; the template is trusted markup. An unknown language falls back to
 * English (the types rule out an unknown key).
 */
export function tr(key: V2Key, lang: BotLang, vars?: TrVars): string {
  const dict = V2_DICTS[lang] ?? en;
  const template: string = dict[key] ?? en[key];
  if (!vars) return template;
  // One pass, so a value that happens to contain "{name}" is never expanded.
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? escapeHtml(String(vars[name])) : whole,
  );
}

/** Is `v` one of the bot languages? */
export function isBotLang(v: unknown): v is BotLang {
  return typeof v === "string" && (BOT_LANGS as readonly string[]).includes(v);
}

// ─── Formatting ─────────────────────────────────────────────────────────────

/** Integer cents → "$12.50". The wallet is in dollars in every language. */
export function fmtUsd(cents: number): string {
  const safe = Number.isFinite(cents) ? Math.round(cents) : 0;
  const sign = safe < 0 ? "-" : "";
  const abs = Math.abs(safe);
  return `${sign}$${Math.floor(abs / 100)}.${String(abs % 100).padStart(2, "0")}`;
}

/** Whole dollars when the amount has no cents ("$5"), else "$5.50". For prices in button labels. */
export function fmtUsdShort(cents: number): string {
  return cents % 100 === 0 ? `$${cents / 100}` : fmtUsd(cents);
}

const DATE_LOCALE: Record<BotLang, string> = { en: "en-GB", ru: "ru-RU", es: "es-ES", de: "de-DE", fr: "fr-FR" };

/** A calendar date in the user's language, in UTC like everything else the bot shows: "12 Nov 2026". */
const EN_MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"] as const;

export function fmtDate(ms: number, lang: BotLang): string {
  if (!Number.isFinite(ms) || ms <= 0) return "-";
  if (lang === "en") {
    // By hand: ICU's en-GB now abbreviates September as "Sept".
    const d = new Date(ms);
    return `${d.getUTCDate()} ${EN_MONTHS[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
  }
  try {
    // Russian: "9 ноября 2026" (the short form ends in "г.", which doubles
    // the full stop of a sentence that ends with the date).
    const parts = new Intl.DateTimeFormat(DATE_LOCALE[lang] ?? "en-GB", {
      day: "numeric",
      month: lang === "ru" ? "long" : "short",
      year: "numeric",
      timeZone: "UTC",
    }).formatToParts(new Date(ms));
    if (lang === "ru") {
      const pick = (type: Intl.DateTimeFormatPartTypes) => parts.find((p) => p.type === type)?.value ?? "";
      return `${pick("day")} ${pick("month")} ${pick("year")}`;
    }
    return parts.map((p) => p.value).join("");
  } catch {
    return new Date(ms).toISOString().slice(0, 10);
  }
}
