/** Провайдеры платежа. Для рублей годятся SMART_GLOCAL и PAY2ME. */
export const LAVA_PROVIDERS = ["SMART_GLOCAL", "UNLIMINT", "PAYPAL", "PAY2ME"] as const;

/** Валюты, которые принимает лава. Больше у неё нет. */
export type LavaCurrency = "RUB" | "USD" | "EUR";

export type LavaMethodId =
  | "card"
  | "applepay"
  | "paypal"
  | "pix"
  | "sepa"
  | "ideal"
  | "mbway"
  | "bancontact";

export interface LavaMethodSpec {
  readonly id: LavaMethodId;
  /** В каких валютах способ доступен. */
  readonly currencies: readonly LavaCurrency[];
  readonly provider: (typeof LAVA_PROVIDERS)[number];
  /** Пусто — провайдер сам себе метод, как у PayPal. */
  readonly method?: string;
  /** Требует имя покупателя в запросе. Без него счёт не выставится. */
  readonly needsFullName?: boolean;
}

/**
 * ЧТО ИМЕННО ПРИНИМАЕТ АККАУНТ — проверено на живом API 25.08.2026 прогоном
 * `scripts/lava-check.mjs --matrix`, а не взято из документации.
 *
 * Три вещи, которые этот прогон выяснил и которые из документации не следуют:
 *
 *   • Лава показывает покупателю РОВНО ОДИН способ на счёт — тот, что назван
 *     при создании. Списка на её странице нет, `CHECKOUT_PAGE` из примеров
 *     молча подменяется картой. Поэтому выбор делается у нас, до перехода.
 *   • В рублях доступны только карта через SMART_GLOCAL и СБП через PAY2ME.
 *     Карта через PAY2ME отвечает «Restricted payment method type».
 *   • Всё остальное — карты Visa и Mastercard, PayPal, Apple Pay и
 *     европейские методы — живёт ТОЛЬКО в долларах и евро.
 *
 * PIX проверен в долларах (лава уводит его провайдеру knx, метод при этом тот
 * же); в евро не проверен, поэтому здесь его нет.
 *
 * РУБЛЁВЫХ СПОСОБОВ ЗДЕСЬ НЕТ НАМЕРЕННО. Лава их умеет — СБП через PAY2ME и
 * карта МИР через SMART_GLOCAL, — но рубли у магазина уже принимают Cashera и
 * ЮKassa, а ценность этой линии в другом: она единственная даёт покупателю
 * из-за рубежа что-то кроме криптовалюты. Держать здесь третий рублёвый путь
 * значило бы удлинять список выбора без единой новой возможности.
 */
export const LAVA_METHODS: readonly LavaMethodSpec[] = [
  { id: "card", currencies: ["USD", "EUR"], provider: "UNLIMINT", method: "CARD" },
  { id: "paypal", currencies: ["USD", "EUR"], provider: "PAYPAL" },
  { id: "applepay", currencies: ["USD", "EUR"], provider: "UNLIMINT", method: "APPLE_PAY" },
  { id: "pix", currencies: ["USD"], provider: "UNLIMINT", method: "PIX" },
  { id: "sepa", currencies: ["EUR"], provider: "UNLIMINT", method: "SEPATRANSFER" },
  { id: "ideal", currencies: ["EUR"], provider: "UNLIMINT", method: "IDEAL" },
  { id: "mbway", currencies: ["EUR"], provider: "UNLIMINT", method: "MBWAY" },
  {
    id: "bancontact",
    currencies: ["EUR"],
    provider: "UNLIMINT",
    method: "BANCONTACT",
    needsFullName: true,
  },
];

/**
 * Нижний порог суммы счёта, ниже которого лава отвечает отказом.
 *
 * ИЗМЕРЕНО СОБСТВЕННОЙ КАССОЙ 26.08.2026, а не прочитано: их спецификация о
 * порогах молчит вовсе, а в ответе на отказ сумма не называется. Рублёвый
 * порог был известен раньше и стоил одного отказа; валютные обнаружились
 * тогда, когда счёт на служебный тариф в 290 ₽ ($3.1) не выставился ВООБЩЕ,
 * тогда как $15.3 тем же способом проходит.
 *
 * Замеры 26.08.2026, каждый — отдельный счёт через собственную кассу:
 *
 *   USD: $3.1 отказ, $4 отказ, $5 ПРИНЯТ, $15.3 принят.
 *   EUR: €2.8 отказ, €3.7 отказ, €4.6 отказ, €5.5 ПРИНЯТ, €7.3 и €13.9 приняты.
 *
 * Отсюда числа ниже. Долларовое зажато точно: между отказом и приёмом ровно
 * рубеж. Евровое взято по НАИМЕНЬШЕЙ ПРИНЯТОЙ сумме, а не по середине вилки
 * 4.6–5.5: правило здесь одно — показанный способ не имеет права отказать, и
 * ради этого лучше не показать способ на 5.2 €, чем довести до отказа.
 *
 * Порог считается свойством валюты, а не способа: перебирать восемь способов
 * в двух валютах значило бы полтора десятка неоплаченных контрактов ради
 * чисел, которые всё равно пришлось бы округлить в безопасную сторону.
 * Замеры сделаны картой (USD) и iDEAL (EUR), оба через UNLIMINT.
 *
 * ЧЕМУ ЭТО МЕШАЕТ НА САМОМ ДЕЛЕ: не тарифам — самый дешёвый в прайсе стоит
 * больше тысячи рублей, — а ДОКУПКЕ. Гигабайт датацентровых стоит 145 ₽, то
 * есть $1.5, и до этой правки покупатель, выбравший lava.top на маленькой
 * докупке, упирался в «не удалось создать счёт» без объяснения.
 */
export const LAVA_MIN_AMOUNT: Record<LavaCurrency, number> = {
  RUB: 50,
  USD: 5,
  EUR: 5.5,
};

/** Валюта линии, пришедшая снаружи. */
export function isLavaCurrency(value: unknown): value is LavaCurrency {
  return value === "RUB" || value === "USD" || value === "EUR";
}

/** Примет ли лава такую сумму. Проверять ДО показа способа покупателю. */
export function lavaTakesAmount(currency: LavaCurrency, amount: number): boolean {
  return Number.isFinite(amount) && amount >= LAVA_MIN_AMOUNT[currency];
}

export function lavaMethod(id: string): LavaMethodSpec | null {
  return LAVA_METHODS.find((m) => m.id === id) ?? null;
}

/** Способы, доступные в этой валюте. Порядок — тот, в котором показывать. */
export function lavaMethodsFor(currency: LavaCurrency): readonly LavaMethodSpec[] {
  return LAVA_METHODS.filter((m) => m.currencies.includes(currency));
}

/**
 * Что показать покупателю при выбранной валюте витрины.
 *
 * Правило: способ идёт в предпочтённой валюте, если он её принимает, иначе в
 * своей первой. Отсюда европеец, читающий по-испански, платит картой в евро, а
 * англоязычный — в долларах; при этом iDEAL, SEPA, MB Way и Bancontact остаются
 * в евро всем, потому что долларовых у них не бывает вовсе, а прятать их от
 * голландца из-за языка интерфейса было бы глупо.
 */
export function lavaMethodChoices(
  preferred: LavaCurrency,
  /**
   * Сколько с покупателя спишут в указанной валюте. Передаётся функцией, а не
   * числом, потому что сумма зависит от валюты, а курс живёт в `currency.ts` —
   * тянуть его сюда значило бы затащить в этот файл половину витрины.
   *
   * Пусто — сумма неизвестна (в докупке она появляется только после логина), и
   * тогда порог не применяется: спрятать способ из-за незнания хуже, чем
   * показать.
   */
  chargeIn?: (currency: LavaCurrency) => number,
): readonly { readonly id: LavaMethodId; readonly currency: LavaCurrency }[] {
  // Валюта витрины больше НЕ решает, показывать ли способы: рублёвых у линии
  // нет вовсе, и русскому покупателю она предлагает ровно то же, что всем
  // остальным. Предпочтение осталось только для выбора между долларом и евро
  // у способов, которые принимают обе валюты.
  return LAVA_METHODS.map((m) => ({
    id: m.id,
    currency: m.currencies.includes(preferred) ? preferred : m.currencies[0],
  })).filter(
    // Способ, которым нельзя заплатить эту сумму, не показывается вовсе.
    // Показать его значило бы довести человека до чужой страницы отказом.
    (c) => chargeIn === undefined || lavaTakesAmount(c.currency, chargeIn(c.currency)),
  );
}
